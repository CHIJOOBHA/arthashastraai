/** Full translation for a language; any key it lacks falls back to English. */
export function getTranslation(language: string): Translation {
  return { ...en, ...(TRANSLATIONS[language] || {}) } as Translation;
}

/** Replaces {name} placeholders: fmt('Used {n}', { n: 3 }). */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
